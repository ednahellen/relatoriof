CREATE TRIGGER `trg_AtualizarEstoque_Entrada` AFTER INSERT ON `tbprodutos` FOR EACH ROW BEGIN
    IF NEW.quantidade > 0 THEN
        INSERT INTO tbEstoqueItens (codList, quantidade, dataMovimentacao, horaMovimentacao)
        VALUES (NEW.codList, NEW.quantidade, CURDATE(), CURTIME())
        ON DUPLICATE KEY UPDATE 
            quantidade = quantidade + NEW.quantidade,
            dataMovimentacao = CURDATE(),
            horaMovimentacao = CURTIME();
    END IF;
END
$$
DELIMITER ;
DELIMITER $$
CREATE TRIGGER `trg_AtualizarEstoque_Saida` AFTER INSERT ON `tbprodutos` FOR EACH ROW BEGIN
    IF NEW.quantidade < 0 THEN
        UPDATE tbEstoqueItens
        SET quantidade = quantidade + NEW.quantidade,
            dataMovimentacao = CURDATE(), 
            horaMovimentacao = CURTIME()
        WHERE codList = NEW.codList;
    END IF;
END
$$
DELIMITER ;
DELIMITER $$
CREATE TRIGGER `trg_ValidarEstoque_Saida` BEFORE INSERT ON `tbprodutos` FOR EACH ROW BEGIN
    DECLARE estoqueAtual INT;
    
    IF NEW.quantidade < 0 THEN
        SELECT COALESCE(quantidade, 0) INTO estoqueAtual
        FROM tbEstoqueItens
        WHERE codList = NEW.codList;
        
        IF estoqueAtual < ABS(NEW.quantidade) THEN
            SIGNAL SQLSTATE '45000'
            SET MESSAGE_TEXT = 'Estoque insuficiente para a saída';
        END IF;
    END IF;
END
$$
